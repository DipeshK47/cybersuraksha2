#!/usr/bin/env node
/**
 * Extract every narrated recap/example step in §§8.3–8.5.
 *
 * The topic panels remain the source of truth. This generator produces:
 *   1. a Python `script.py` consumed by the existing H100 Chatterbox pipeline;
 *   2. a typed step-signature -> audio URL manifest consumed by Explainer3D.
 *
 * Run from cybersuraksha with Node 22:
 *   node scripts/build-chapter8-panel-narration.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "@babel/parser";

const here = dirname(fileURLToPath(import.meta.url));
const academy = resolve(here, "..");
const repo = resolve(academy, "..");
const chapterDir = resolve(academy, "app/grade/[grade]/[subject]/[chapter]");
const pythonDir = resolve(repo, "class10_modules/maths/video/topics/panels");
const manifestPath = resolve(chapterDir, "chapter8-narration.generated.ts");

// IDs are `${section}-${indexWithinThatFile}`, so adding sources cannot renumber
// the existing 8-3 / 8-4 clips — each file numbers independently.
const sources = [
  { section: "8-1", path: resolve(chapterDir, "topic-panels.tsx") },
  { section: "8-2", path: resolve(chapterDir, "topic-panels-8-2.tsx") },
  { section: "8-3", path: resolve(chapterDir, "topic-panels-8-3.tsx") },
  { section: "8-4", path: resolve(chapterDir, "topic-panels-8-4.tsx") },
];

function propName(node) {
  return node?.key?.name ?? node?.key?.value;
}

function stringsFromArray(node) {
  if (node?.type !== "ArrayExpression") return [];
  return node.elements
    .filter((item) => item?.type === "StringLiteral")
    .map((item) => item.value);
}

function collectStepObjects(node, output) {
  if (!node || typeof node !== "object") return;
  if (node.type === "ObjectExpression") {
    const props = new Map(
      node.properties
        .filter((item) => item.type === "ObjectProperty")
        .map((item) => [propName(item), item.value]),
    );
    const caption = props.get("caption");
    if (caption?.type === "StringLiteral") {
      output.push({
        caption: caption.value,
        math: stringsFromArray(props.get("math")),
        answer: props.get("answer")?.type === "StringLiteral"
          ? props.get("answer").value
          : undefined,
        narrationSrc: props.get("narrationSrc")?.type === "StringLiteral"
          ? props.get("narrationSrc").value
          : undefined,
      });
    }
  }
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) value.forEach((item) => collectStepObjects(item, output));
    else if (value && typeof value === "object") collectStepObjects(value, output);
  }
}

function speakMath(value) {
  return value
    .replaceAll("√", " square root of ")
    .replaceAll("²", " squared ")
    .replaceAll("³", " cubed ")
    .replaceAll("°", " degrees ")
    .replaceAll("θ", " theta ")
    .replaceAll("∠", " angle ")
    .replaceAll("△", " triangle ")
    .replaceAll("→", " becomes ")
    .replaceAll("↔", " swaps with ")
    .replaceAll("≤", " is less than or equal to ")
    .replaceAll("≥", " is greater than or equal to ")
    .replaceAll("≠", " is not equal to ")
    .replaceAll("−", " minus ")
    .replaceAll("×", " times ")
    .replaceAll("÷", " divided by ")
    .replaceAll("/", " divided by ")
    .replaceAll("=", " equals ")
    .replace(/\s+/g, " ")
    .trim();
}

function narrationFor(step) {
  const board = [...step.math, step.answer].filter(Boolean).map(speakMath);
  if (!board.length) return step.caption;
  return `${step.caption} Follow the calculation on the board, one line at a time. ${board.join(". Then, ")}.`;
}

const jobs = [];
for (const source of sources) {
  const code = await readFile(source.path, "utf8");
  const ast = parse(code, { sourceType: "module", plugins: ["typescript", "jsx"] });
  const steps = [];
  collectStepObjects(ast, steps);
  steps.forEach((step, index) => {
    jobs.push({
      ...step,
      id: `${source.section}-${String(index + 1).padStart(3, "0")}`,
      narration: narrationFor(step),
    });
  });
}

await mkdir(pythonDir, { recursive: true });
const pyLines = jobs.map((job) =>
  `    (${JSON.stringify(job.id)}, ${JSON.stringify(job.narration)}, .82, .30, .12),`,
).join("\n");
await writeFile(
  resolve(pythonDir, "script.py"),
  `"""Generated by cybersuraksha/scripts/build-chapter8-panel-narration.mjs."""\n\n` +
    `LINES = [\n${pyLines}\n]\n` +
    `BEATS = [("all", "Chapter 8 interactive teaching", LINES)]\n`,
);

const narrationKey = (job) => JSON.stringify([
  job.caption,
  job.math,
  job.answer ?? null,
]);
const manifestKeys = new Set();
const entries = jobs.filter((job) => !job.narrationSrc).map((job) => {
  const key = narrationKey(job);
  if (manifestKeys.has(key)) {
    throw new Error(`Duplicate narration signature needs an explicit narrationSrc: ${job.caption}`);
  }
  manifestKeys.add(key);
  return `  ${JSON.stringify(key)}: { src: ${JSON.stringify(`/audio/chapter8/${job.id}.mp3`)} },`;
}).join("\n");
await writeFile(
  manifestPath,
  `/* Generated by scripts/build-chapter8-panel-narration.mjs. Do not hand-edit. */\n` +
    `export type StepNarration = { src: string };\n\n` +
    `export const chapter8NarrationKey = (caption: string, math: string[] = [], answer?: string) =>\n` +
    `  JSON.stringify([caption, math, answer ?? null]);\n\n` +
    `export const CHAPTER8_NARRATION: Readonly<Record<string, StepNarration>> = {\n${entries}\n};\n`,
);

console.log(`Generated ${jobs.length} narrated steps (${manifestKeys.size} manifest lookups, ${jobs.length - manifestKeys.size} explicit sources).`);
console.log(`Python: ${pythonDir}/script.py`);
console.log(`Manifest: ${manifestPath}`);
